        lines.append("|---|---|")
        for cat, count in sorted(by_cat.items()):
            lines.append(f"| {cat} | {count} |")
        lines.append("")
        
        # Risks by severity
        sorted_risks = sorted(risks, key=lambda r: 
            {'CRITICAL': 0, 'HIGH': 1, 'MEDIUM': 2, 'LOW': 3}.get(r.severity, 4))
        
        current_sev = None
        for r in sorted_risks:
            if r.severity != current_sev:
                current_sev = r.severity
                icon = sev_icons.get(r.severity, '')
                lines.append(f"---\n")
