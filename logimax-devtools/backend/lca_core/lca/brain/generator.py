class DBAnalyzer:
    """Analyze database schema and extract status code distributions."""
    
    def __init__(self, db_config: Optional[Dict] = None):
        self.db_config = db_config or {}
    
    def get_table_schema(self, table_name: str, database: str = 'retail_dev') -> List[Dict]:
        """Get column definitions for a table. Returns raw data for external query."""
        return {
            'sql': f"SELECT COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT "
                   f"FROM INFORMATION_SCHEMA.COLUMNS "
                   f"WHERE TABLE_SCHEMA = '{database}' AND TABLE_NAME = '{table_name}' "
                   f"ORDER BY ORDINAL_POSITION",
            'table': table_name
        }
    
    def get_status_code_query(self, table_name: str, columns: List[str]) -> str:
        """Generate SQL to get value distribution for status-like columns."""
        unions = []
        for col in columns:
            unions.append(
                f"SELECT '{col}' as col_name, CAST({col} AS CHAR) as val, COUNT(*) as cnt "
                f"FROM {table_name} GROUP BY {col}"
            )
        return " UNION ALL ".join(unions) + " ORDER BY col_name, val"
    
    @staticmethod
    def detect_status_columns(columns: List[Dict]) -> List[str]:
        """Detect which columns are likely status/flag columns."""
        status_patterns = [
            'status', 'type', 'is_', 'flag', 'mode', 'state',
            'category', 'level', 'priority', 'role'
        ]
        result = []
        for col in columns:
            name = col.get('COLUMN_NAME', '').lower()
            col_type = col.get('COLUMN_TYPE', '').lower()
            
            if any(p in name for p in status_patterns):
                if 'int' in col_type or 'tinyint' in col_type or 'enum' in col_type:
                    result.append(col['COLUMN_NAME'])
            
            if name in ('bill_type', 'item_type', 'payment_mode', 'mc_type',
                       'bill_discount_type', 'calculation_based_on', 'billing_for',
                       'make_as_advance', 'salesTransType', 'receipt_type'):
                if name not in result:
                    result.append(name)
        
        return result


