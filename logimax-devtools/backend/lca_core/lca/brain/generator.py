class BrainDocGenerator:
    """Generate the 6 brain v2.0 documents from extracted data."""
    
    def __init__(self, module: str, result: BrainBuildResult):
        self.module = module
        self.result = result
        self.now = datetime.now().strftime('%Y-%m-%d')
    
    def generate_wiring(self) -> str:
        """Generate WIRING.md — fully automated, no human review needed."""
        lines = [
            f"# {self.module.title()} Module — Wiring Map (Brain v2.0)",
            f"",
            f"> Auto-generated by `lca brain-build` on {self.now}",
            f"> Source: Code analysis of {len(self.result.controller_files)} controller(s), "
            f"{len(self.result.model_files)} model(s), {len(self.result.js_files)} JS file(s)",
            f"",
            f"---",
            f"",
        ]
        
        # v1.1: Duplicate methods warning
        if self.result.duplicate_methods:
            lines.append("## ⚠️ Duplicate Methods Detected\n")
            lines.append("| First Definition | Duplicate |")
            lines.append("|---|---|")
            for first, dup in self.result.duplicate_methods:
                lines.append(f"| `{first}` | `{dup}` |")
            lines.append("")
        
        # Controllers
        lines.append("## Controllers\n")
        for ctrl_file in self.result.controller_files:
            ctrl_methods = [m for m in self.result.methods if m.file_path == str(ctrl_file)]
            fname = Path(ctrl_file).name
            total_lines = sum(m.line_count for m in ctrl_methods)
            lines.append(f"### {fname} ({len(ctrl_methods)} methods, {total_lines:,} lines)\n")
            lines.append(f"| Method | Line | Lines | Tables Written | Tables Read | Traits |")
            lines.append(f"|---|---|---|---|---|---|")
            for m in sorted(ctrl_methods, key=lambda x: x.start_line):
                written = ', '.join(m.tables_insert + m.tables_update + m.tables_delete) or '-'
                read = ', '.join(m.tables_select) or '-'
                # v1.1: Show method traits
                traits = []
                if m.has_transaction: traits.append('TXN')
                if m.has_json_response: traits.append('JSON')
                if m.has_otp: traits.append('OTP')
                if m.has_file_upload: traits.append('UPLOAD')
                if m.line_count > 500: traits.append('⚠️MEGA')
                elif m.line_count > 200: traits.append('⚠️LARGE')
                traits_str = ', '.join(traits) or '-'
                lines.append(
                    f"| `{m.name}()` | {m.start_line} | {m.line_count} | {written} | {read} | {traits_str} |"
                )
            lines.append("")
        
        # Models
        lines.append("## Models\n")
        for model_file in self.result.model_files:
            model_methods = [m for m in self.result.methods if m.file_path == str(model_file)]
            fname = Path(model_file).name
            total_lines = sum(m.line_count for m in model_methods)
            lines.append(f"### {fname} ({len(model_methods)} methods, {total_lines:,} lines)\n")
            lines.append(f"| Method | Line | Lines | Tables | Traits |")
            lines.append(f"|---|---|---|---|---|")
            for m in sorted(model_methods, key=lambda x: x.start_line):
                all_tables = set(m.tables_insert + m.tables_update + m.tables_delete + m.tables_select)
                tables = ', '.join(sorted(all_tables)) or '-'
                traits = []
                if m.has_transaction: traits.append('TXN')
                if m.line_count > 200: traits.append('⚠️LARGE')
                traits_str = ', '.join(traits) or '-'
                lines.append(f"| `{m.name}()` | {m.start_line} | {m.line_count} | {tables} | {traits_str} |")
            lines.append("")
        
        # v1.1: JS files with actual data
        if self.result.js_data:
            lines.append("## JS Files\n")
            for js_path, js_info in self.result.js_data.items():
                fname = Path(js_path).name
                lines.append(f"### {fname} ({len(js_info['functions'])} functions, {js_info['line_count']} lines)\n")
                if js_info['ajax_urls']:
                    lines.append(f"**AJAX Endpoints:**")
                    for url in js_info['ajax_urls'][:20]:
                        lines.append(f"- `{url}`")
                    lines.append("")
                # Top functions by name (first 20)
                if js_info['functions']:
                    lines.append(f"**Key Functions:** " + 
                                ', '.join(f"`{f['name']}()`" for f in js_info['functions'][:20]))
                    if len(js_info['functions']) > 20:
                        lines.append(f"  ... and {len(js_info['functions']) - 20} more")
                lines.append("")
        
        # Views
        if self.result.view_files:
            lines.append("## Views\n")
            # v1.1: Group views by subdirectory
            view_groups = {}
            for v in sorted(self.result.view_files):
                parts = Path(v).parts
                # Find the views/ parent and get the first subdir after it
                try:
                    views_idx = list(parts).index('views')
                    group = parts[views_idx + 1] if views_idx + 1 < len(parts) else 'root'
                except ValueError:
                    group = 'other'
                view_groups.setdefault(group, []).append(v)
            
            for group, files in sorted(view_groups.items()):
                lines.append(f"### {group}/ ({len(files)} files)\n")
                for v in files:
                    fname = Path(v).name
                    purpose = self._infer_view_purpose(fname)
                    
                    # v2.0: Include parsed view data if available
                    view_info = self.result.view_data.get(v, {})
                    if view_info:
                        fields = len(view_info.get('form_fields', []))
                        hidden = len(view_info.get('hidden_settings', []))
                        val_maps = len(view_info.get('value_label_maps', {}))
                        tabs = view_info.get('tabs', [])
                        model_calls = view_info.get('model_calls', [])
                        css_lines = view_info.get('inline_css_lines', 0)
                        lc = view_info.get('line_count', 0)
                        
                        detail_parts = [purpose]
                        detail_parts.append(f"{lc} lines")
                        if fields: detail_parts.append(f"{fields} form fields")
                        if hidden: detail_parts.append(f"{hidden} hidden settings")
                        if val_maps: detail_parts.append(f"{val_maps} value maps")
                        if css_lines: detail_parts.append(f"{css_lines}L inline CSS")
                        
                        lines.append(f"- `{fname}` — {', '.join(detail_parts)}")
                        
                        if tabs:
                            tab_str = ' → '.join([f"`{t['label']}`" for t in tabs])
                            lines.append(f"  - Tabs: {tab_str}")
                        if model_calls:
                            lines.append(f"  - Model calls: {', '.join(model_calls[:8])}")
                    else:
                        lines.append(f"- `{fname}` — {purpose}")
                lines.append("")
        
        # v2.2: AJAX Route summary (full map in AJAX_ROUTES.md)
        if self.result.ajax_routes:
            total = sum(len(m) for m in self.result.ajax_routes.values())
            matched = sum(1 for c in self.result.ajax_routes.values() 
                         for s in c.values() if s == 'matched')
            cross = sum(1 for c in self.result.ajax_routes.values() 
                       for s in c.values() if s == 'cross-module')
            unmatched = total - matched - cross
            lines.append(f"## AJAX Routes Summary\n")
            lines.append(f"> Full map: see `AJAX_ROUTES.md`\n")
            lines.append(f"- **{total}** total endpoints across **{len(self.result.ajax_routes)}** controllers")
            lines.append(f"- ✅ {matched} matched | 🔗 {cross} cross-module | ❌ {unmatched} unmatched")
            lines.append("")
        
        # Tables
        lines.append("## Database Tables\n")
        
        # v2.2: Add row count column if DB data available
        has_db = bool(self.result.db_row_counts)
        
        lines.append("### Owned (Written by this module)\n")
        if has_db:
            lines.append("| Table | Rows | INSERT | UPDATE | DELETE |")
            lines.append("|---|---|---|---|---|")
        else:
            lines.append("| Table | INSERT | UPDATE | DELETE |")
            lines.append("|---|---|---|---|")
        for t in sorted(self.result.tables_owned):
            inserters = [m.name for m in self.result.methods if t in m.tables_insert]
            updaters = [m.name for m in self.result.methods if t in m.tables_update]
            deleters = [m.name for m in self.result.methods if t in m.tables_delete]
            if has_db:
                row_count = self.result.db_row_counts.get(t, 0)
                row_str = f"{row_count:,}" if row_count > 0 else "0"
                lines.append(
                    f"| `{t}` | {row_str} | {', '.join(inserters[:5]) or '-'} | "
                    f"{', '.join(updaters[:5]) or '-'} | {', '.join(deleters[:5]) or '-'} |"
                )
            else:
                lines.append(
                    f"| `{t}` | {', '.join(inserters[:5]) or '-'} | "
                    f"{', '.join(updaters[:5]) or '-'} | {', '.join(deleters[:5]) or '-'} |"
                )
        
        lines.append("\n### Referenced (Read by this module)\n")
        if has_db:
            lines.append("| Table | Rows | Read By |")
            lines.append("|---|---|---|")
        else:
            lines.append("| Table | Read By |")
            lines.append("|---|---|")
        for t in sorted(self.result.tables_referenced):
            readers = [m.name for m in self.result.methods if t in m.tables_select]
            if has_db:
                row_count = self.result.db_row_counts.get(t, '-')
                row_str = f"{row_count:,}" if isinstance(row_count, int) and row_count > 0 else str(row_count)
                lines.append(f"| `{t}` | {row_str} | {', '.join(set(readers[:5])) or '-'} |")
            else:
                lines.append(f"| `{t}` | {', '.join(set(readers[:5])) or '-'} |")
        
        return '\n'.join(lines)
    
    def _infer_view_purpose(self, filename: str) -> str:
        """Infer view purpose from filename patterns."""
        name = filename.lower().replace('.php', '')
        if 'form' in name: return 'Data entry form'
        if 'list' in name: return 'DataTable list view'
        if 'print' in name or 'invoice' in name or 'receipt' in name: return 'Print/PDF template'
        if 'edit' in name: return 'Edit form'
        if 'format' in name: return 'Print format template'
        if 'thermal' in name: return 'Thermal print template'
        if 'soft_copy' in name: return 'Soft copy view'
        if 'approval' in name: return 'Approval list'
        if 'split' in name: return 'Bill split view'
        if 'pos' in name: return 'POS integration'
        if 'delivery' in name: return 'Delivery tracking'
        if 'cash' in name: return 'Cash management'
        if 'adjustment' in name: return 'Adjustment form'
        if 'transfer' in name: return 'Transfer form/list'
        if 'payment' in name: return 'Payment view'
        if 'designer' in name: return 'Template designer'
        return 'View'
    
    def generate_status_codes(self) -> str:
        """Generate STATUS_CODES.md from code analysis + DB data."""
        lines = [
            f"# {self.module.title()} Module — Status Codes & Magic Values (Brain v2.0)",
            f"",
            f"> Auto-generated by `lca brain-build` on {self.now}",
            f"",
            f"---",
            f"",
        ]
        
        # v1.1: Generate from code analysis even without DB
        if not self.result.status_codes:
            # Extract all status checks from methods
            all_checks = {}
            for m in self.result.methods:
                for check in m.status_checks:
                    if '=' in check and not check.startswith('$type='):
                        col, val = check.split('=', 1)
                        key = f"{col}"
                        if key not in all_checks:
                            all_checks[key] = {}
                        if val not in all_checks[key]:
                            all_checks[key][val] = []
                        all_checks[key][val].append(m.name)
            
            if all_checks:
                lines.append("## From Code Analysis (no DB data yet)\n")
                lines.append("> Run with `--db` flag or provide DB query results for actual value counts\n")
                
                for col in sorted(all_checks.keys()):
                    values = all_checks[col]
                    lines.append(f"### `{col}`\n")
                    lines.append(f"| Value | Used In | Meaning |")
                    lines.append(f"|---|---|---|")
                    for val in sorted(values.keys()):
                        methods = ', '.join(sorted(set(values[val])))
                        # v1.3: Auto-fill meaning from SQL IF chain maps
                        meaning = '[CONFIRM]'
                        if col in self.result.value_maps and val in self.result.value_maps[col]:
                            meaning = self.result.value_maps[col][val]
                        lines.append(f"| {val} | {methods} | {meaning} |")
                    lines.append("")
            else:
                lines.append("*No status checks detected from code. Run with DB data for complete results.*\n")
        
        # DB-sourced status codes
        if self.result.status_codes:
            by_table = {}
            for sc in self.result.status_codes:
                key = f"{sc.table}.{sc.column}"
                if key not in by_table:
                    by_table[key] = []
                by_table[key].append(sc)
            
            lines.append("## From Database\n")
            for key in sorted(by_table.keys()):
                items = by_table[key]
                table, col = key.split('.', 1)
                lines.append(f"### {table} — `{col}`\n")
                lines.append(f"| Value | Count | Meaning | Confirmed |")
                lines.append(f"|---|---|---|---|")
                for item in sorted(items, key=lambda x: str(x.value)):
                    meaning = item.meaning or "[CONFIRM]"
                    confirmed = "✅" if item.confirmed else "❓"
                    lines.append(f"| {item.value} | {item.count} | {meaning} | {confirmed} |")
                lines.append("")
        
        # v2.2: DB Discoveries section
        if self.result.db_discoveries:
            discoveries = self.result.db_discoveries
            
            new_vals = discoveries.get('new_values_not_in_code', [])
            code_only = discoveries.get('code_values_not_in_db', [])
            
            if new_vals:
                lines.append("---\n")
                lines.append("## ⚠️ DB Values NOT Handled in Code\n")
                lines.append("> These values exist in the database but have no corresponding logic in PHP/JS.\n")
                lines.append("> This could indicate: missing handlers, dead data, or features added via direct DB.\n")
                lines.append("| Table | Column | Value | DB Count | Note |")
                lines.append("|---|---|---|---|---|")
                for d in new_vals:
                    lines.append(
                        f"| `{d['table']}` | `{d['column']}` | {d['value']} | "
                        f"{d['count']} | {d.get('note', '')} |"
                    )
                lines.append("")
            
            if code_only:
                lines.append("## 📋 Code Values NOT in Database\n")
                lines.append("> These values are handled in code but have 0 rows in the dev DB.\n")
                lines.append("> Could be: unused features, other-env-only features, or recently added.\n")
                lines.append("| Table | Column | Value | Code Label | Note |")
                lines.append("|---|---|---|---|---|")
                for d in code_only:
                    lines.append(
                        f"| `{d['table']}` | `{d['column']}` | {d['value']} | "
                        f"{d.get('meaning', '?')} | {d.get('note', '')} |"
                    )
                lines.append("")
        
        return '\n'.join(lines)
    
    def generate_review_tracker(self) -> str:
        """Generate REVIEW_TRACKER.md with all Q&A items."""
        lines = [
            f"# {self.module.title()} Module — Brain v2.0 Review Tracker",
            f"",
            f"> Generated: {self.now}",
            f"> Total items: {len(self.result.review_items)}",
            f"> Status: PENDING review",
            f"",
            f"## How to Use",
            f"",
            f"1. Go through each question in order",
            f"2. Write your answer in the `**Your answer:**` field", 
            f"3. Change status from `PENDING` to `CONFIRMED` or `CORRECTED`",
            f"4. Run `lca brain-build {self.module} --finalize` when done",
            f"",
            f"## Progress",
            f"",
        ]
        
        pending = sum(1 for r in self.result.review_items if r.status == 'PENDING')
        confirmed = sum(1 for r in self.result.review_items if r.status == 'CONFIRMED')
        lines.append(f"- Pending: {pending}")
        lines.append(f"- Confirmed: {confirmed}")
        lines.append(f"- Total: {len(self.result.review_items)}")
        lines.append("")
        
        categories = {}
        for item in self.result.review_items:
            if item.category not in categories:
                categories[item.category] = []
            categories[item.category].append(item)
        
        for cat in ['STATUS', 'RULE', 'FLOW', 'RISK', 'PATTERN', 'DUPLICATE']:
            if cat not in categories:
                continue
            items = categories[cat]
            lines.append(f"---")
            lines.append(f"")
            lines.append(f"## {cat} Questions ({len(items)} items)")
            lines.append(f"")
            
            for item in items:
                lines.append(f"### {item.id} | {item.category} | {item.status} | Priority: {item.priority}")
                lines.append(f"")
                lines.append(f"**Code:** `{item.code_ref}`")
                lines.append(f"**AI observes:** {item.ai_observation}")
                lines.append(f"**Question:** {item.question}")
                lines.append(f"**Your answer:** {item.human_answer or '___'}")
                lines.append(f"")
        
        return '\n'.join(lines)
    
    def generate_ajax_routes(self) -> str:
        """Generate AJAX_ROUTES.md — JS AJAX URL → PHP controller method mapping."""
        if not self.result.ajax_routes:
            return ""
        
        lines = [
            f"# {self.module.title()} Module — AJAX Route Map (Brain v2.2)",
            f"",
            f"> Auto-generated by `lca brain-build` on {self.now}",
            f"> Maps JS AJAX URLs to PHP controller methods",
            f"",
            f"---",
            f"",
        ]
        
        total = sum(len(m) for m in self.result.ajax_routes.values())
        matched = sum(1 for c in self.result.ajax_routes.values() 
                     for s in c.values() if s == 'matched')
        cross = sum(1 for c in self.result.ajax_routes.values() 
                   for s in c.values() if s == 'cross-module')
        unmatched = total - matched - cross
        
        lines.append(f"## Coverage\n")
        lines.append(f"| Metric | Count |")
        lines.append(f"|---|---|")
        lines.append(f"| Total endpoints | {total} |")
        lines.append(f"| ✅ Matched | {matched} |")
        lines.append(f"| 🔗 Cross-module | {cross} |")
        lines.append(f"| ❌ Unmatched | {unmatched} |")
        lines.append(f"| Controllers called | {len(self.result.ajax_routes)} |")
        lines.append("")
        
        for ctrl in sorted(self.result.ajax_routes.keys()):
            methods = self.result.ajax_routes[ctrl]
            m_count = sum(1 for s in methods.values() if s == 'matched')
            c_count = sum(1 for s in methods.values() if s == 'cross-module')
            u_count = sum(1 for s in methods.values() if s not in ('matched', 'cross-module'))
            
            if c_count > 0 or u_count > 0:
                label = "🔗" if c_count > 0 else "⚠️"
            else:
                label = "✅"
            
            lines.append(f"### {label} {ctrl} ({len(methods)} endpoints)\n")
            
            if c_count > 0 or u_count > 0:
                lines.append("| Method | Status |")
                lines.append("|---|---|")
                for method in sorted(methods.keys()):
                    status = methods[method]
                    icon = {'matched': '✅', 'cross-module': '🔗', 
                            'unmatched': '❌', 'missing-controller': '💀'}.get(status, '?')
                    lines.append(f"| `{method}()` | {icon} {status} |")
                lines.append("")
            else:
                method_list = ', '.join(f'`{m}()`' for m in sorted(methods.keys())[:15])
                if len(methods) > 15:
                    method_list += f' ... +{len(methods)-15} more'
                lines.append(f"{method_list}\n")
        
        return '\n'.join(lines)
    
