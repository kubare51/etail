            if cat not in by_cat:
                continue
            
            lines.append(f"---\n")
            lines.append(f"## {cat} Flows\n")
            
            for f in by_cat[cat]:
                lines.append(f"### {f.id}: {f.title}\n")
                
                # Attributes
                attrs = []
                if f.entry_method:
                    lines.append(f"- **Entry:** `{f.entry_method}()` ({f.entry_file})")
                if f.line_count:
                    lines.append(f"- **Size:** {f.line_count:,} lines")
                
                flags = []
                if f.has_transaction: flags.append('🔒 Transaction')
                if f.has_otp: flags.append('🔑 OTP')
                if f.has_json_response: flags.append('📡 JSON')
                if flags:
                    lines.append(f"- **Traits:** {' | '.join(flags)}")
                
                if f.table_write_sequence:
                    lines.append(f"- **Writes:** {' → '.join('`' + t + '`' for t in f.table_write_sequence[:8])}")
                
