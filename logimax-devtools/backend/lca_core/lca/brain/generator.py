        lines.append("## Risk Summary\n")
        lines.append("| Severity | Count |")
        lines.append("|---|---|")
        sev_icons = {'CRITICAL': '🔴', 'HIGH': '🟠', 'MEDIUM': '🟡', 'LOW': '🟢'}
        for sev in ['CRITICAL', 'HIGH', 'MEDIUM', 'LOW']:
            if sev in by_sev:
                lines.append(f"| {sev_icons.get(sev, '')} {sev} | {by_sev[sev]} |")
        lines.append("")
        
        # Category summary
        by_cat = {}
        for r in risks:
            by_cat.setdefault(r.category, 0)
            by_cat[r.category] += 1
        
